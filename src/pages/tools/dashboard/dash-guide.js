export function guideChapterHtml(id, query = '') {
  if (id === 'recipes') return renderRecipes(query);
  if (id === 'gloss') return renderGlossary(query);
  const sections = GUIDE[id] || GUIDE.start;
  const q = query.trim().toLowerCase();
  const filtered = q ? sections.filter((s) =>
    s.h.toLowerCase().includes(q) || s.body.toLowerCase().replace(/<[^>]+>/g, ' ').includes(q)
  ) : sections;
  if (!filtered.length) return '<div class="dash-empty">بخشی پیدا نشد. عبارت دیگری جستجو کن.</div>';
  return filtered.map((s) => `<article class="dash-guide-sec"><h3>${esc(s.h)}</h3><div>${s.body}</div></article>`).join('');
}

export function guideSearchAll(query) {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  const out = [];
  for (const [chId, sections] of Object.entries(GUIDE)) {
    const ch = GUIDE_CHAPTERS.find((c) => c.id === chId);
    sections.forEach((s) => {
      const text = (s.h + ' ' + s.body.replace(/<[^>]+>/g, ' ')).toLowerCase();
      if (text.includes(q)) {
        const idx = text.indexOf(q);
        const plain = s.body.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ');
        const pIdx = Math.max(0, plain.toLowerCase().indexOf(q) - 40);
        out.push({ chId, chTitle: ch ? ch.icon + ' ' + ch.title : chId, h: s.h, snippet: '…' + plain.slice(pIdx, pIdx + 120) + '…' });
      }
    });
    if (out.length > 20) return out;
  }
  return out.slice(0, 20);
}
