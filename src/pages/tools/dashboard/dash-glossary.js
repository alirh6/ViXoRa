export function renderGlossary(query = '') {
  const q = query.trim().toLowerCase();
  const list = q ? GLOSSARY.filter((g) => (g.term + g.def).toLowerCase().includes(q)) : GLOSSARY;
  if (!list.length) return '<div class="dash-empty">واژه‌ای پیدا نشد.</div>';
  return `<div class="dash-hint">📚 ${list.length} واژه</div>` + list.map((g) =>
    `<div class="dash-gloss"><b>${esc(g.term)}</b><p>${esc(g.def)}</p></div>`).join('');
}
