export function quoteOfDay(cat = '') {
  const pool = cat ? QUOTES.filter((q) => q[2] === cat) : QUOTES;
  const list = pool.length ? pool : QUOTES;
  return list[Math.floor(Date.now() / 86400000) % list.length];
}
export function randomQuote(cat = '') {
  const pool = cat ? QUOTES.filter((q) => q[2] === cat) : QUOTES;
  const list = pool.length ? pool : QUOTES;
  return list[Math.floor(Math.random() * list.length)];
}
