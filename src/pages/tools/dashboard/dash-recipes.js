export const DIFF_FA = { easy: 'آسان', mid: 'متوسط', hard: 'پیشرفته' };

export function renderRecipes(query = '') {
  const q = query.trim().toLowerCase();
  const list = q ? RECIPES.filter((r) =>
    (r.title + r.steps.join(' ') + (r.tip || '')).toLowerCase().includes(q)
  ) : RECIPES;
  if (!list.length) return '<div class="dash-empty">دستورپختی پیدا نشد.</div>';
  return list.map((r, i) => `<article class="dash-recipe">
    <h3>${r.icon} ${esc(r.title)} <span class="dash-diff dash-diff-${r.diff === 'easy' ? 'easy' : r.diff === 'mid' ? 'mid' : 'hard'}">${DIFF_FA[r.diff]} • ⏱ ${esc(r.time)}</span></h3>
    <ol>${r.steps.map((s) => `<li>${esc(s)}</li>`).join('')}</ol>
    ${r.tip ? `<div class="dash-hint">💡 ${esc(r.tip)}</div>` : ''}
  </article>`).join('');
}

export function recipeCount() { return RECIPES.length; }
