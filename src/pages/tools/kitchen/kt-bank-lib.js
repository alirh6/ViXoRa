// 📚 کتابخانهٔ ساخت دستورهای بانک غذای آشپزخانه — الگوی سازنده + ابزارهای مشترک
// فرمت فشرده: هر دستور یک فراخوان X با رشته‌های جداشده با «|» که اینجا به
// اسکیمای کامل Kitchen OS باز می‌شود (کاملاً سازگار با RECIPES فعلی).

const I = (k, q, u, aisle = 'other', sub = '') => ({ k, q, u, aisle, sub });
const S = (t, sec = 0) => ({ t, sec });

/** پارس مواد: 'نام|مقدار|واحد|راهرو|جایگزین' — آیتم‌ها با '؛' جداشده‌اند */
const parseIngs = (str) => str.split('؛').filter(Boolean).map((p) => {
  const [k, q, u, aisle, sub] = p.split('|').map((x) => (x || '').trim());
  return I(k, Number(q) || q || '', u || 'pcs', aisle || 'other', sub || '');
});
const parseSteps = (str) => str.split(/\s*[|؛]\s*/).map((t) => S(t.trim())).filter((s) => s.t);
const TAGS = (s) => s.split('|').map((t) => t.trim()).filter(Boolean);

/**
 * X(id,name,cat,meal,time,diff,tags,ings,steps,tips,meta)
 * tags/ings/steps: رشتهٔ جداشده؛ tips: متن؛ meta: {srv,kcal,p,c,f,veg,vegan,gluten,dairy,nut,spice,cost,season,region}
 */
export function X(id, n, cat, meal, time, diff, tags, ings, steps, tips, meta = {}) {
  return {
    id, name: n, cat, meal, time, diff,
    tags: TAGS(tags),
    ings: parseIngs(ings),
    steps: parseSteps(steps),
    tips,
    srv: 4, kcal: 400, p: 20, c: 40, f: 16,
    veg: false, vegan: false, gluten: true, dairy: false, nut: false,
    spice: 1, cost: 2, season: 'همه', region: 'ایران',
    ...meta,
  };
}

